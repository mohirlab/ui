// Builds @mohirlab/icons from src/svg/*.svg.
// Sources are plain SVG so designers can round-trip them through any editor.
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = join(root, 'src/svg');
const dist = join(root, 'dist');

/** Default presentation, applied by renderers rather than stored per icon. */
export const STROKE = {
  fill: 'none',
  stroke: 'currentColor',
  'stroke-width': '1.75',
  'stroke-linecap': 'square',
  'stroke-linejoin': 'miter',
  'stroke-miterlimit': '4',
};

const ALLOWED = new Set(['path', 'circle', 'rect', 'line', 'polyline', 'polygon', 'ellipse']);

/** Parse the flat, self-closing element list our sources use. */
export function parseIcon(name, svg) {
  const problems = [];
  if (!/viewBox="0 0 24 24"/.test(svg)) problems.push('viewBox must be "0 0 24 24"');
  const nodes = [];
  for (const [, tag, attrs] of svg.matchAll(/<(\w+)\s([^>]*?)\/>/g)) {
    if (!ALLOWED.has(tag)) {
      problems.push(`<${tag}> is not allowed`);
      continue;
    }
    const props = Object.fromEntries([...attrs.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, k, v]) => [k, v]));
    for (const key of ['fill', 'stroke']) {
      if (props[key] && !['none', 'currentColor'].includes(props[key])) {
        problems.push(`${tag} ${key}="${props[key]}": use currentColor or none`);
      }
    }
    nodes.push([tag, props]);
  }
  if (!nodes.length) problems.push('no drawable elements');
  if (problems.length) throw new Error(`${name}.svg: ${problems.join('; ')}`);
  return nodes;
}

const camel = (name) => name.replace(/-(\w)/g, (_, c) => c.toUpperCase());
const exportName = (name) => `icon${camel(name).replace(/^\w/, (c) => c.toUpperCase())}`;
const attrs = (props) =>
  Object.entries(props)
    .map(([k, v]) => ` ${k}="${v}"`)
    .join('');
const markup = (nodes) => nodes.map(([tag, props]) => `<${tag}${attrs(props)}/>`).join('');

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const icons = readdirSync(srcDir)
    .filter((f) => f.endsWith('.svg'))
    .toSorted()
    .map((file) => {
      const name = file.replace(/\.svg$/, '');
      if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(name)) throw new Error(`${file}: use kebab-case names`);
      return { name, nodes: parseIcon(name, readFileSync(join(srcDir, file), 'utf8')) };
    });

  rmSync(dist, { recursive: true, force: true });
  mkdirSync(join(dist, 'svg'), { recursive: true });

  const header = '// Generated by scripts/build.mjs. Do not edit.\n';
  let js = header;
  let dts =
    header +
    'export type IconNode = readonly [tag: string, attributes: Readonly<Record<string, string>>];\n' +
    'export interface IconData { readonly name: IconName; readonly nodes: readonly IconNode[] }\n' +
    `export type IconName = ${icons.map((i) => JSON.stringify(i.name)).join(' | ')};\n` +
    'export declare const iconNames: readonly IconName[];\n' +
    'export declare const defaultAttributes: Readonly<Record<string, string>>;\n' +
    'export interface ToSvgOptions { size?: number | string; strokeWidth?: number | string; title?: string; className?: string }\n' +
    '/** Render an icon to an SVG string, for any framework or none. */\n' +
    'export declare function toSvg(icon: IconData, options?: ToSvgOptions): string;\n';

  js += `export const defaultAttributes = ${JSON.stringify(STROKE)};\n`;
  js += `export const iconNames = ${JSON.stringify(icons.map((i) => i.name))};\n`;
  js += `const escape = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
export function toSvg(icon, { size = 24, strokeWidth, title, className } = {}) {
  const base = { ...defaultAttributes, ...(strokeWidth == null ? {} : { 'stroke-width': String(strokeWidth) }) };
  const head = Object.entries(base).map(([k, v]) => \` \${k}="\${v}"\`).join('');
  const a11y = title ? \` role="img" aria-label="\${escape(title)}"\` : ' aria-hidden="true"';
  const cls = className ? \` class="\${escape(className)}"\` : '';
  const body = icon.nodes.map(([tag, p]) => \`<\${tag}\${Object.entries(p).map(([k, v]) => \` \${k}="\${v}"\`).join('')}/>\`).join('');
  return \`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="\${size}" height="\${size}"\${head}\${cls}\${a11y}>\${title ? \`<title>\${escape(title)}</title>\` : ''}\${body}</svg>\`;
}
`;
  for (const { name, nodes } of icons) {
    const id = exportName(name);
    js += `/** ${name} */\nexport const ${id} = /* @__PURE__ */ Object.freeze({ name: ${JSON.stringify(name)}, nodes: ${JSON.stringify(nodes)} });\n`;
    dts += `export declare const ${id}: IconData;\n`;
    writeFileSync(
      join(dist, 'svg', `${name}.svg`),
      `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="24" height="24"${attrs(STROKE)}>${markup(nodes)}</svg>\n`,
    );
  }
  writeFileSync(join(dist, 'index.js'), js);
  writeFileSync(join(dist, 'index.d.ts'), dts);

  writeFileSync(
    join(dist, 'sprite.svg'),
    `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n${icons
      .map(
        ({ name, nodes }) =>
          `  <symbol id="ml-icon-${name}" viewBox="0 0 24 24"${attrs(STROKE)}>${markup(nodes)}</symbol>`,
      )
      .join('\n')}\n</svg>\n`,
  );
  writeFileSync(
    join(dist, 'icons.json'),
    JSON.stringify(
      { attributes: STROKE, icons: Object.fromEntries(icons.map((i) => [i.name, i.nodes])) },
      null,
      2,
    ) + '\n',
  );
  console.log(`@mohirlab/icons: built ${icons.length} icons.`);
}
