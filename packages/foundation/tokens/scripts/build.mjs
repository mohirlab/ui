import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { toCssBlock, toFlatJson, toTypeLiteral, toValues, validate } from './transform.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (file) => JSON.parse(readFileSync(file, 'utf8'));

const primitivesDir = join(root, 'src/primitives');
const primitives = Object.assign(
  {},
  ...readdirSync(primitivesDir)
    .filter((f) => f.endsWith('.json'))
    .toSorted()
    .map((f) => read(join(primitivesDir, f))),
);
const modes = {
  light: read(join(root, 'src/semantic/light.json')),
  dark: read(join(root, 'src/semantic/dark.json')),
};

// Layering rule: semantic tokens alias primitives only, never other semantic tokens.
const contextFor = () => primitives;

const problems = [
  ...validate(primitives).map((p) => `primitives > ${p}`),
  ...Object.entries(modes).flatMap(([name, tree]) =>
    validate(tree, contextFor(tree)).map((p) => `${name} > ${p}`),
  ),
];
if (problems.length === 0) {
  // Every mode must define exactly the same semantic keys, or themes break.
  const [lightKeys, darkKeys] = [modes.light, modes.dark].map((m) =>
    Object.keys(toFlatJson(m, contextFor(m))),
  );
  for (const key of lightKeys) if (!darkKeys.includes(key)) problems.push(`dark > missing ${key}`);
  for (const key of darkKeys) if (!lightKeys.includes(key)) problems.push(`light > missing ${key}`);
}
if (problems.length) {
  console.error(`Token validation failed:\n  ${problems.join('\n  ')}`);
  process.exit(1);
}

const values = toValues(primitives);
const modeValues = Object.fromEntries(
  Object.entries(modes).map(([name, tree]) => [name, toValues(tree, contextFor(tree))]),
);

const dist = join(root, 'dist');
mkdirSync(dist, { recursive: true });

const header = '// Generated by scripts/build.mjs. Do not edit.\n';
let js = header;
let dts = header;
for (const [group, value] of Object.entries(values)) {
  js += `export const ${group} = ${JSON.stringify(value, null, 2)};\n`;
  dts += `export declare const ${group}: ${toTypeLiteral(value)};\n`;
}
js += `export const modes = ${JSON.stringify(modeValues, null, 2)};\n`;
dts += `export declare const modes: ${toTypeLiteral(modeValues)};\n`;
dts += `export type ModeName = keyof typeof modes;\n`;
dts += `export type SemanticTokens = (typeof modes)['light'];\n`;
writeFileSync(join(dist, 'index.js'), js);
writeFileSync(join(dist, 'index.d.ts'), dts);

writeFileSync(
  join(dist, 'tokens.css'),
  '/* @mohirlab/tokens: generated CSS custom properties for consumers without Vanilla Extract. */\n' +
    toCssBlock(':root', primitives) +
    toCssBlock(':root, [data-ml-mode="light"]', modes.light, contextFor(modes.light)) +
    toCssBlock('[data-ml-mode="dark"]', modes.dark, contextFor(modes.dark)),
);

const flat = { ...toFlatJson(primitives) };
for (const [name, tree] of Object.entries(modes)) {
  for (const [k, v] of Object.entries(toFlatJson(tree, contextFor(tree)))) flat[`${name}.${k}`] = v;
}
writeFileSync(join(dist, 'tokens.json'), JSON.stringify(flat, null, 2) + '\n');

console.log(`@mohirlab/tokens: built ${Object.keys(flat).length} tokens.`);
